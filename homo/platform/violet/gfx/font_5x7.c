struct font font_5x7;

/* Composed letters a broadcast SSID or a file name can carry that the 8-bit
 * table cannot index: two rows of diacritic on top of the compressed body.
 * Drawn in the same grid and the same bit packing (5 columns in bits 5..1). */
/* columns are bits 5..1, so 0x08 is the third column and 0x04 the fourth:
 * the mark starts left of centre and falls right, which is a grave. */
static const uint8_t row_a_grave[7]    = { 0x08, 0x04, 0x18, 0x04,
                                           0x1c, 0x24, 0x1e }; /* U+00E0 */
static const uint8_t row_o_circ_dot[7] = { 0x08, 0x14, 0x1c, 0x22,
                                           0x22, 0x1c, 0x08 }; /* U+1ED9 */

static const struct font_glyph ext_glyphs[2] = {
    {5, 7, 6, 0, 0, row_a_grave},
    {5, 7, 6, 0, 0, row_o_circ_dot},
};
static const uint32_t ext_cp[2] = { 0x00E0, 0x1ED9 };

