const struct font_glyph *font_5x7_ext(uint32_t cp) {
    for (size_t i = 0; i < sizeof(ext_cp) / sizeof(ext_cp[0]); i++)
        if (ext_cp[i] == cp)
            return &ext_glyphs[i];
    for (size_t i = 0; i < sizeof(latin1_base) / sizeof(latin1_base[0]); i++) {
        if (latin1_base[i].cp == cp)
            return &glyphs[(unsigned char)latin1_base[i].base - 32];
    }
    return NULL;
}

void font_5x7_init(void) {
    font_init(&font_5x7, glyphs, 32, 126, 7);
    font_5x7.ext = font_5x7_ext;
}
