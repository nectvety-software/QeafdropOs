/* gui/gfx/font_5x7.c - 5x7 bitmap font for ASCII 32..126
 *
 * Glyph bitmaps are the classic fixed-space 5x7 font published in
 * Adafruit-GFX-Library/glcdfont.c (BSD-3-Clause), mechanically
 * transposed from 5 column bytes to 7 row bytes. Each row keeps its
 * 5 pixel columns in bits 5..1 (pattern << 1), which is what
 * font_draw_char() and apps/recovery/ text_v() decode.
 *
 * This replaces the original hand-written table, whose round letters
 * carried a stray left column and whose V/W/M/N glyphs were wrong.
 */

